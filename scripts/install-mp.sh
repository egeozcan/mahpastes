#!/usr/bin/env bash
# Install (or remove) the mp CLI together with its shell completions and man
# pages, for the current user.
#
# Usage: scripts/install-mp.sh [--uninstall] [path/to/mp]
#
# Locations (override with PREFIX, BINDIR, DATAROOT; no root access needed):
#   $BINDIR/mp                                          default $PREFIX/bin
#   $DATAROOT/bash-completion/completions/mp            default $PREFIX/share
#   $DATAROOT/zsh/site-functions/_mp
#   $DATAROOT/fish/vendor_completions.d/mp.fish        only when fish is installed
#   $DATAROOT/man/man1/mp*.1
# PREFIX defaults to ~/.local. Completions and man pages are generated by the
# binary being installed, so they always match it.
set -euo pipefail

repo="$(cd "$(dirname "$0")/.." && pwd)"
PREFIX="${PREFIX:-$HOME/.local}"
BINDIR="${BINDIR:-$PREFIX/bin}"
DATAROOT="${DATAROOT:-$PREFIX/share}"

bash_dir="$DATAROOT/bash-completion/completions"
zsh_dir="$DATAROOT/zsh/site-functions"
# fish reads per-user completions from $XDG_DATA_HOME/fish/vendor_completions.d
# (and <dir>/fish/vendor_completions.d for each XDG_DATA_DIRS entry), not
# from share/fish/completions.
fish_dir="$DATAROOT/fish/vendor_completions.d"
man_dir="$DATAROOT/man/man1"

uninstall=0
src=""
for arg in "$@"; do
    case "$arg" in
        --uninstall) uninstall=1 ;;
        *) src="$arg" ;;
    esac
done
src="${src:-$repo/build/bin/mp}"

# Remove the man pages a previous install generated. Only pages whose .TH
# line names mahpastes as the source are touched, so another tool's mp-*.1 in
# a shared man directory (say PREFIX=/usr/local) survives.
remove_man_pages() {
    local page
    for page in "$man_dir"/mp.1 "$man_dir"/mp-*.1; do
        [[ -f "$page" ]] || continue
        if grep -q '^\.TH .*"mahpastes"' "$page" 2>/dev/null; then
            rm -f "$page"
        fi
    done
}

if ((uninstall)); then
    rm -f "$BINDIR/mp" "$bash_dir/mp" "$zsh_dir/_mp" "$fish_dir/mp.fish"
    remove_man_pages
    echo "Removed $BINDIR/mp and its shell completions and man pages from $DATAROOT"
    exit 0
fi

# -f, not -x: archive extractors do not always keep the executable bit, and
# install(1) sets the mode anyway.
if [[ ! -f "$src" ]]; then
    echo "$src not found; run 'make mp' first." >&2
    exit 1
fi

mkdir -p "$BINDIR"
install -m 755 "$src" "$BINDIR/mp"
echo "Installed mp to $BINDIR/mp"

# Completion scripts do not need the app or an API key.
install_completion() { # shell dest
    mkdir -p "$(dirname "$2")"
    "$BINDIR/mp" completion "$1" >"$2.tmp" && mv "$2.tmp" "$2" || { rm -f "$2.tmp"; echo "warning: could not write $2" >&2; }
}
install_completion bash "$bash_dir/mp"
install_completion zsh "$zsh_dir/_mp"
if command -v fish >/dev/null 2>&1 || [[ -d "${XDG_CONFIG_HOME:-$HOME/.config}/fish" ]]; then
    install_completion fish "$fish_dir/mp.fish"
fi

# Start from a clean set so pages of commands that no longer exist go away.
mkdir -p "$man_dir"
remove_man_pages
"$BINDIR/mp" gendocs --man "$man_dir" || echo "warning: could not install man pages" >&2

echo "Installed shell completions (bash, zsh, fish when present) and man pages under $DATAROOT"
case ":$PATH:" in *:"$BINDIR":*) ;; *) echo "Add $BINDIR to PATH to run 'mp' directly." ;; esac
# zsh does not export FPATH, so this cannot tell whether ~/.zshrc already
# adds the directory; only remind zsh users.
if [[ "${SHELL##*/}" == zsh ]]; then
    echo "zsh: unless ~/.zshrc already does, add 'fpath=($zsh_dir \$fpath)' before 'compinit' to enable completion."
fi
